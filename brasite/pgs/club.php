  <h2>Broadcasting from the heart of the Peak District…</h2>

  <h1>‘Buxton Radio Amateur Society’</h1>

<div>

<p>
We are based in the fabulous spa town of Buxton in the heart of the beautiful Peak District. Buxton is famous for its mineral water - Buxton Water. Buxton Radio Amateur Society has roots that stretch back some 40 years and consits of a group of like-minded individuals.
</p>

<p>
Paying testament to the friendliness of the club, we have members who are happy to travel some considerable distances to meet up regularly. We have members from over the county, the borders of Manchester and Staffordshire, we have members based in the north of Scotland and even one member flying the flag over in Spain!
</p>

<p>
Obviously we have more than enough capability to stay in contact with each other through the various frequencies that we are allowed to use however
 as with many other organisations and clubs over the past few years BRA has adapted to the issues that we have been faced with.  During the pandemic
 of 2020, we moved the ‘face to face’ meeting onto the zoom platform as a further way of keeping in contact. This proved to be very successful as it
 allowed our remote members to be able to keep involved and to this day has been a successful way for us to meet up and we still do this weekly on
 the 2nd, 3rd & 4th Tuesday evening of the month.
</p>

<p>
For the 1st Tuesday of the month, we meet at the community fire station where we are able to set up antennas and radios (both analogue and digital)
 and see who is out there to make contact with. Some of the evenings are used for training and as every day is a school day, we can all learn
 something. Broadcast, listen, training or social chat we always know we can expect and evening of coffee, biscuits and friendship.
</p>
